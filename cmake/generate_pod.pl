# Generate a POD file from an OpenSSL doc/man*/*.pod.in template the way
# util/dofile.pl does (with -s doc/perlvars.pm), without needing configdata.
#
# Usage:
#   generate_pod.pl <openssl_src_dir> <input.pod.in> <output.pod> <min_api> <deprecated_3_0 (0|1)>

use strict;
use warnings;
use File::Basename qw(dirname);
use File::Path qw(make_path);
use File::Spec::Functions qw(abs2rel catfile rel2abs);

die "usage: $0 <openssl_src_dir> <input.pod.in> <output.pod> <min_api> <deprecated_3_0>\n"
    unless @ARGV == 5;

my ($src, $in, $out, $min_api, $deprecated_3_0) = @ARGV;
$src = rel2abs($src);
$in  = rel2abs($in);
$out = rel2abs($out);

unshift @INC, catfile($src, 'util', 'perl'),
              catfile($src, 'external', 'perl', 'Text-Template-1.56', 'lib');
require OpenSSL::fallback;
OpenSSL::fallback->import(catfile($src, 'external', 'perl', 'MODULES.txt'));
require OpenSSL::Template;
OpenSSL::Template->import();

# perlvars.pm refers to the lexical @autowarntext, as in util/dofile.pl
my @autowarntext = (
    "WARNING: do not edit!",
    "Generated by generate_pod.pl from " . abs2rel($in, $src)
);
{
    # perlvars.pm says "use configdata;" but uses nothing from it
    $INC{'configdata.pm'} = __FILE__;
    my $vars = catfile($src, 'doc', 'perlvars.pm');
    open my $fh, '<', $vars or die "Couldn't open $vars, $!\n";
    my $contents = do { local $/; <$fh> };
    close $fh;
    eval $contents;
    die $@ if $@;
}

my %config = (
    openssl_api_defines => [ "OPENSSL_CONFIGURED_API=$min_api" ],
);
my %disabled = ();
$disabled{'deprecated-3.0'} = 'option' unless $deprecated_3_0;

my $template = OpenSSL::Template->new(TYPE => 'FILE', SOURCE => $in)
    or die "Cannot open template $in: $OpenSSL::Template::ERROR\n";
my $result = $template->fill_in(
    HASH => {
        config       => \%config,
        target       => {},
        disabled     => \%disabled,
        autowarntext => \@autowarntext,
    },
    OUTPUT => undef,
);
die "Failed to fill template $in: $OpenSSL::Template::ERROR\n" unless defined $result;

make_path(dirname($out));
my $tmp = "$out.tmp$$";
open my $ofh, '>', $tmp or die "Cannot write $tmp: $!\n";
print $ofh $result;
close $ofh or die "Cannot close $tmp: $!\n";
rename $tmp, $out or die "Cannot rename $tmp to $out: $!\n";
